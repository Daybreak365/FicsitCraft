def validate_small(b, ymax):
    for i, p in enumerate(b.parts):
        (x0, y0, z0), (x1, y1, z1) = p['from'], p['to']
        if min(x0, y0, z0) < -1e-6 or x1 > 1 + 1e-6 or z1 > 1 + 1e-6 or y1 > ymax:
            raise SystemExit('%s: part %d out of bounds %s %s' % (b.name, i, p['from'], p['to']))
    # the two lamp volumes must stay empty
    if b.name.startswith('rail_signal'):
        for i, p in enumerate(b.parts):
            (x0, y0, z0), (x1, y1, z1) = p['from'], p['to']
            for (ly0, ly1) in ((3.55, 3.89), (3.11, 3.45)):
                if x0 < 0.67 and x1 > 0.33 and y0 < ly1 and y1 > ly0 and z0 < 0.79 and z1 > 0.75:
                    raise SystemExit('%s: part %d intrudes into a lamp volume' % (b.name, i))



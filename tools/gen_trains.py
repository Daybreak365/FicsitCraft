# stacked-box cylinders (tanks, pipes, stubs)
# ------------------------------------------------------------------------------------------------------------------
def tube(b, axis, c0, c1, R, a0, a1, color, bands=(), seams=(), steps=None, decor=None, cap0='plain', cap1='plain',
         soot=0.0, share=None, flags=(), kind='metal'):
    """Cylinder along `axis` built from stacked boxes (an octagon-ish prism, like fluid_buffer).

    axis 'z': c0 = centre x, c1 = centre y, a0..a1 = z range;  'x': c0 = centre z, c1 = centre y, a0..a1 = x range;
    'y': c0 = centre x, c1 = centre z, a0..a1 = y range.  bands = (along0, along1, colour); seams = along positions.
    decor(level, face) -> list of decals for that face (level 0 = middle box, +n upper, -n lower).
    Shading comes from the true surface normal at each pixel, so all boxes read as one round body.
    """
    if steps is None:
        steps = 3 if R >= 0.75 else (2 if R >= 0.2 else 1)
    if steps == 3:
        bnd, hws = [0, 0.45, 0.8, 1.0], [0.95, 0.78, 0.46]
    elif steps == 2:
        bnd, hws = [0, 0.6, 1.0], [0.93, 0.56]
    else:
        bnd, hws = [0, 1.0], [1.0]
    levels = [(0, -bnd[1], bnd[1], hws[0])]
    for i in range(1, steps):
        levels.append((i, bnd[i], bnd[i + 1], hws[i]))
        levels.append((-i, -bnd[i + 1], -bnd[i], hws[i]))
    along_faces = {'z': ('left', 'right', 'up', 'down'), 'x': ('front', 'back', 'up', 'down'),
                   'y': ('front', 'back', 'left', 'right')}[axis]
    lo_face = {'z': 'down', 'x': 'down', 'y': 'back'}[axis]   # face toward -q
    hi_face = {'z': 'up', 'x': 'up', 'y': 'front'}[axis]      # face toward +q
    for (lvl, q0, q1, hw) in levels:
        p0, p1 = c0 - hw * R, c0 + hw * R
        qa, qb = c1 + q0 * R, c1 + q1 * R
        if axis == 'z':
            box = (p0, qa, a0, p1, qb, a1)
        elif axis == 'x':
            box = (a0, qa, p0, a1, qb, p1)
        else:
            box = (p0, a0, qa, p1, a1, qb)
        faces = {}
        for f in FACES:
            if f in along_faces:
                base = tube_base(box, axis, c0, c1, R, color, bands, seams, soot, kind=kind)
            else:
                base = tube_base(box, axis, c0, c1, R, color, cap_style=(cap0 if _is_low_cap(axis, f) else cap1), kind=kind)
            faces[f] = F(base, *(decor(lvl, f) if decor else []))
        # faces buried inside the neighbouring level are never seen
        if lvl > 0:
            faces[lo_face] = DOWN_ID[0]
        elif lvl < 0:
            faces[hi_face] = DOWN_ID[0]
        b.box(*box, share=(None if share is None else '%s/%d' % (share, lvl)), flags=flags, **faces)


def _is_low_cap(axis, face):
    """True for the cap at the low end of the axis range."""
    return {'z': 'back', 'x': 'left', 'y': 'down'}[axis] == face


CORRIDOR = (1.1, 3.9)


def validate(b):
    """Buildings: nothing but the ballast/sleeper/rail strip may enter the track corridor above y = 0.4."""
    bad = []
    for i, p in enumerate(b.parts):
        (x0, y0, z0), (x1, y1, z1) = p['from'], p['to']
        if x1 > CORRIDOR[0] + 1e-6 and x0 < CORRIDOR[1] - 1e-6 and y1 > 0.4 + 1e-6:
            bad.append((i, p['from'], p['to']))
        if min(x0, x1) < -0.05 or max(x0, x1) > W_B + 0.05 or z0 < -0.05 or z1 > D_B + 0.05 or y1 > b.h + 1e-6:
            bad.append((i, 'outside footprint', p['from'], p['to']))
    if bad:
        raise SystemExit('%s: geometry violates the corridor / footprint rules: %s' % (b.name, bad[:6]))



class TB(Building):
    """Building box DSL bound to the trn texture namespace, with geometry going to buildings/ or vehicles/."""

    def __init__(self, store, name, w, d, h, ax, az, kind='buildings', geo_name=None):
        super().__init__(store, name, w, d, h, ax, az)
        self.kind = kind
        self.geo_name = geo_name or name
        self.particle = None
        self.shared = None

    def box(self, x0, y0, z0, x1, y1, z1, all=None, flags=(), tint=None, active=None, share=None, **faces):
        """Like Building.box.  `down` defaults to the shared dark underside.  `share='key'` paints each face once per
        (key, face) and re-uses it for every later box with that key (posts, bollards, wheels ... equal small parts)."""
        x0, y0, z0, x1, y1, z1 = [round(v, 4) for v in (x0, y0, z0, x1, y1, z1)]
        if 'down' not in faces:
            faces['down'] = DOWN_ID[0]
        if share is not None:
            dims = {'front': (x1 - x0, y1 - y0), 'back': (x1 - x0, y1 - y0), 'left': (z1 - z0, y1 - y0),
                    'right': (z1 - z0, y1 - y0), 'up': (x1 - x0, z1 - z0), 'down': (x1 - x0, z1 - z0)}
            side = faces.pop('sides', None)
            spec = {f: all for f in FACES}
            if side is not None:
                for f in ('front', 'back', 'left', 'right'):
                    spec[f] = side
            spec.update(faces)
            faces = {}
            for f in FACES:
                fs = spec[f]
                if fs is None:
                    fs = GN()
                if isinstance(fs, F):
                    fs = self.shared.get('%s/%s' % (share, f), fs, dims[f][0], dims[f][1], f)
                faces[f] = fs
            if active:
                active = {f: (self.shared.get('%s/%s_on' % (share, f), fs, dims[f][0], dims[f][1], f)
                              if isinstance(fs, F) else fs) for f, fs in active.items()}
            all = None
        return super().box(x0, y0, z0, x1, y1, z1, all=all, flags=flags, tint=tint, active=active, **faces)

    def export(self):
        geo = GEO_B if self.kind == 'buildings' else GEO_V
        if self.kind == 'buildings':
            validate(self)
        ids = set()
        for p in self.parts:
            ids |= set(p['tex'].values())
            ids |= set(p.get('active', {}).values())
        write_json(os.path.join(geo, self.geo_name + '.json'),
                   {'footprint': [self.w, self.d, self.h, self.ax, self.az], 'parts': self.parts},
                   '%s geometry: %d boxes, %d distinct textures' % (self.kind[:-1], len(self.parts), len(ids)))
        if self.item:
            gb.ITEM_MODELS = ITEM_MODELS
            self.export_item_model()
            p = os.path.join(ITEM_MODELS, self.name + '.json')
            with open(p) as f:
                m = json.load(f)
            if self.particle:
                m['textures']['particle'] = self.particle
            with open(p, 'w') as f:
                json.dump(m, f, indent=1)
            WRITTEN.append((relp(p), '3D item miniature (%d elements)' % len(m['elements'])))

    item = True



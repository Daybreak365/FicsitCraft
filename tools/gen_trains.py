def validate_vehicle(b, L, top=3.62):
    bad = []
    for i, p in enumerate(b.parts):
        (x0, y0, z0), (x1, y1, z1) = p['from'], p['to']
        if y0 < -1e-6 or y1 > top or x0 < 0.1 - 1e-6 or x1 > 2.9 + 1e-6 or z0 < -1e-6 or z1 > L + 1e-6:
            bad.append((i, p['from'], p['to']))
    if bad:
        raise SystemExit('%s: vehicle geometry out of bounds: %s' % (b.name, bad[:6]))


def wheel(b, xc, zc, R=0.45, w=0.16):
    """Stepped-octagon wheel from three non-overlapping boxes; every wheel of the same size shares its textures."""
    cy = R
    hw, hc = 0.93 * R, 0.56 * R
    for i, (dz, y0, y1) in enumerate(((hw, cy - 0.6 * R, cy + 0.6 * R), (hc, cy + 0.6 * R, cy + R), (hc, cy - R, cy - 0.6 * R))):
        canon = (-w / 2, y0, -dz, w / 2, y1, dz)
        b.box(xc - w / 2, y0, zc - dz, xc + w / 2, y1, zc + dz, all=F(wheel_face(canon, 0, cy, 0, R)),
              share='wheel%d_%d' % (int(R * 100), i), flags=['wheel'])



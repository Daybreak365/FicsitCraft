def _indicator(on):
    def fn(cv):
        cv.fill(C('#0C1014'))
        W, H = cv.W, cv.H
        cv.frame(0, 0, W, H, STEEL_D, 1)
        # left arrow (green: straight) and right arrow (amber: diverging)
        for (cx, col, d) in ((0.27, GREEN, -1), (0.73, C('#FFB03A'), 1)):
            c = col if on else col * 0.3
            x = int(cx * W)
            y = H // 2
            hh = max(2, H // 3)
            for k in range(hh):
                cv.rect(x - d * (hh // 2) + d * k, y - (hh - k) // 1 // 2, x - d * (hh // 2) + d * k + 1, y + (hh - k) // 2 + 1, c)
            cv.rect(x + d * 1, y - 1, x + d * (hh // 2 + 3), y + 1, c)
        cv.clean[:] = 1 if on else 0
    return fn



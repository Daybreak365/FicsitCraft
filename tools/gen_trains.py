def rail_top():
    def fn(cv):
        t = np.broadcast_to(cv.ub() / cv.fw, (cv.H, cv.W))
        prof = np.abs(t - 0.5) * 2
        k = 0.62 + 0.4 * (1 - prof ** 1.6)
        cv.a[:] = STEEL[None, None, :] * k[..., None]
        band = np.clip(1 - (prof / 0.6) ** 2, 0, 1)[..., None]
        cv.a[:] = cv.a * (1 - 0.75 * band) + STEEL_L * 1.08 * (0.75 * band)
        cv.a *= (1 + 0.04 * cv.lownoise(0.5))[..., None]
        return 'metal'

    return fn



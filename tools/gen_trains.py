LIGHT3 = np.array([-0.35, 0.85, 0.35], np.float32)
LIGHT3 /= np.linalg.norm(LIGHT3)
HALF3 = LIGHT3 + np.array([0, 0.3, 1.0], np.float32)
HALF3 /= np.linalg.norm(HALF3)


def shade_normal(nx, ny, nz, spec=0.25, base=0.52, gain=0.62):
    d = np.clip(nx * LIGHT3[0] + ny * LIGHT3[1] + nz * LIGHT3[2], 0, 1)
    h = np.clip(nx * HALF3[0] + ny * HALF3[1] + nz * HALF3[2], 0, 1)
    return base + gain * d + spec * h ** 24


def tube_base(box, axis, c0, c1, R, color, bands=(), seams=(), soot=0.0, rings_every=None, cap_style='plain',
              seam_col=None, kind='metal'):
    """Base painter for a face of an axis-aligned cylinder approximated by stacked boxes.

    axis 'z': c0 = centre x, c1 = centre y (axis along z);  'x': c0 = centre z, c1 = centre y;  'y': c0 = centre x, c1 = centre z.
    bands: (along0, along1, colour);  seams: along positions of weld seams.
    """

    def fn(cv):
        X, Y, Z = coords(cv, cv.face, box)
        if axis == 'z':
            a, b, al = X - c0, Y - c1, Z
        elif axis == 'x':
            a, b, al = Z - c0, Y - c1, X
        else:
            a, b, al = X - c0, Z - c1, Y
        r = np.hypot(a, b)
        face_along = {'z': ('left', 'right', 'up', 'down'), 'x': ('front', 'back', 'up', 'down'),
                      'y': ('front', 'back', 'left', 'right')}[axis]
        if cv.face in face_along:
            rr = np.maximum(r, 1e-6)
            na, nb = a / rr, b / rr
            if axis == 'z':
                sh = shade_normal(na, nb, 0.0)
            elif axis == 'x':
                sh = shade_normal(0.0, nb, na)
            else:
                sh = shade_normal(na, 0.0, nb)
            col = np.zeros((cv.H, cv.W, 3), np.float32) + np.asarray(color, np.float32)
            for (z0, z1, c) in bands:
                m = (al >= z0) & (al < z1)
                col[m] = c
            cv.a[:] = col * sh[..., None]
            for s in seams:
                m = np.abs(al - s) < 0.5 / cv.sx if cv.side else np.abs(al - s) < 0.5 / cv.sy
                m = np.abs(al - s) < 0.022
                cv.a[m] *= 0.62
                m2 = (al - s >= 0.022) & (al - s < 0.05)
                cv.a[m2] *= 1.18
            if soot:
                v = np.clip((b + R) / (2 * R), 0, 1)
                s = np.clip(1 - v * 1.5, 0, 1) * soot
                cv.a *= (1 - 0.55 * s)[..., None]
            return kind
        # end cap: spherical shading, weld rings
        rn = np.clip(r / R, 0, 1.2)
        nz = np.sqrt(np.clip(1 - rn ** 2, 0, 1))
        sgn = {'front': 1, 'back': -1, 'right': 1, 'left': -1, 'up': 1, 'down': -1}[cv.face]
        an, bn = a / R, b / R
        if axis == 'z':
            sh = shade_normal(an, bn, nz * sgn)
        elif axis == 'x':
            sh = shade_normal(nz * sgn, bn, an)
        else:
            sh = shade_normal(an, nz * sgn, bn)
        cv.a[:] = np.asarray(color, np.float32) * sh[..., None] * 0.92
        for rr_, dark in ((0.93, 0.6), (0.62, 0.7)):
            m = np.abs(rn - rr_) < 0.03
            cv.a[m] *= dark
        if cap_style == 'manway':
            m = rn < 0.22
            cv.a[m] = np.asarray(STEEL_D, np.float32) * sh[m][:, None]
            m = np.abs(rn - 0.22) < 0.03
            cv.a[m] *= 0.5
        elif cap_style == 'vent':
            cv.a[rn < 0.5] = BLACK
        elif cap_style == 'glowhole':
            cv.a[rn < 0.5] = C('#2A1208')
        elif cap_style == 'pipe':
            # open pipe mouth: dark bore, bright blue lip, bolted flange
            cv.a[rn < 0.56] = C('#07131B')
            cv.a[(rn >= 0.56) & (rn < 0.66)] = BLUE * sh[(rn >= 0.56) & (rn < 0.66)][:, None]
            cv.a[(rn >= 0.4) & (rn < 0.56)] *= 0.75
            for k in range(8):
                ang = k * math.pi / 4 + 0.2
                bx, by = an * 0 + math.cos(ang) * 0.82, bn * 0 + math.sin(ang) * 0.82
                m = np.hypot(an - bx, bn - by) < 0.075
                cv.a[m] = STEEL_L * 0.9
        return kind

    return fn


def wheel_face(box, cx, cy, cz, R, hub=0.14):
    """Locomotive wheel: steel disc with rim, spokes and hub; box faces slice it (coordinates relative to the centre)."""

    def fn(cv):
        X, Y, Z = coords(cv, cv.face, box)
        r = np.hypot(Z - cz, Y - cy) / R
        ang = np.arctan2(Y - cy, Z - cz)
        if cv.face in ('left', 'right'):
            cv.a[:] = STEEL_D * 1.05
            web = (r > 0.3) & (r <= 0.72)
            spokes = web & (np.abs(np.sin(ang * 3)) > 0.8)
            cv.a[web] = GUN * 1.05
            cv.a[spokes] = STEEL * 0.95
            cv.a[(r > 0.72) & (r <= 0.84)] = STEEL_D * 0.9
            cv.a[(r > 0.84) & (r <= 0.96)] = STEEL * 1.0
            cv.a[(r > 0.96)] = GUN * 0.8
            cv.a[(np.abs(r - 0.72) < 0.03)] *= 0.55
            cv.a[r < 0.3] = STEEL * 0.9
            cv.a[r < 0.2] = ORANGE_D
            cv.a[r < 0.1] = BLACK
            sh = 1 + 0.25 * np.cos(ang - 2.3) * (r > 0.84)
            cv.a *= sh[..., None]
        else:
            cv.a[:] = STEEL * 0.78
            cv.a *= (0.85 + 0.15 * np.sin((Z + Y) * 40))[..., None]
        return 'metal'

    return fn


def dot_grid(cv, x0, y0, x1, y1, step, c, r=1):
    for y in range(y0, y1, step):
        for x in range(x0, x1, step):
            cv.rect(x, y, x + r, y + r, c)



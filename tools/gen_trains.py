def windshield(lit=False, tint=C('#3C7DA6')):
    """Wide windscreen: sky reflection over a dark cab; the dashboard, seat backs and roof lamp are painted in behind
    the glass (they glow when the train runs)."""

    def fn(cv):
        cv.vgrad(0, 0, cv.W, cv.H, tint * (1.0 if lit else 0.86), tint * 0.42)
        W, H = cv.W, cv.H
        # room interior behind the glass
        cv.rect(1, int(H * 0.5), W - 1, H - 1, C('#0F1F2B') if not lit else C('#3A3428'), 0.8)
        # dashboard band + screens
        dy = int(H * 0.72)
        cv.rect(1, dy, W - 1, H - 1, C('#15181C'))
        for i, cx in enumerate((0.22, 0.5, 0.78)):
            sx0, sx1 = int(W * (cx - 0.11)), int(W * (cx + 0.11))
            cv.rect(sx0, dy + 2, sx1, dy + max(4, int(H * 0.16)), (C('#7FE8FF') if lit else C('#1B3442')))
            if lit:
                cv.rect(sx0 + 1, dy + 3, sx0 + 1 + (sx1 - sx0) // 2, dy + 4, WHITE, 0.7)
        # seat backs
        for cx in (0.3, 0.7):
            cv.rect(int(W * (cx - 0.09)), int(H * 0.42), int(W * (cx + 0.09)), dy, C('#1A2A38') if not lit else C('#4A3E30'))
        # cab roof lamp
        if lit:
            cv.rect(int(W * 0.44), 1, int(W * 0.56), max(3, int(H * 0.08)), C('#FFF0B0'))
        # glare
        u = np.arange(W)[None, :] + np.arange(H)[:, None] * 0.9
        streak = ((np.mod(u, 46) < 7) | ((np.mod(u + 20, 46) < 2)))
        cv.a[streak] = cv.a[streak] * 0.78 + 255 * 0.22
        t = max(2, int(0.06 * cv.sx))
        cv.frame(0, 0, W, H, GUN, t)
        cv.bevel(0, 0, W, H)
        cv.rect(int(W * 0.5) - 1, 0, int(W * 0.5) + 1, H, GUN) if False else None
        cv.clean[:] = 1
        return 'none'

    return fn


def sidewin(lit=False, tint=C('#3C7DA6')):
    """Sliding side window strip: reflection + hint of the lit cab behind it."""

    def fn(cv):
        cv.vgrad(0, 0, cv.W, cv.H, tint * (1.0 if lit else 0.85), tint * (0.5 if lit else 0.38))
        if lit:
            cv.rect(2, cv.H // 2, cv.W - 2, cv.H - 2, C('#FFD98A'), 0.35)
        u = np.arange(cv.W)[None, :] + np.arange(cv.H)[:, None] * 1.1
        streak = (np.mod(u, 40) < 6)
        cv.a[streak] = cv.a[streak] * 0.8 + 255 * 0.2
        t = max(1, int(0.05 * cv.sy))
        cv.frame(0, 0, cv.W, cv.H, GUN, t)
        cv.rect(cv.W // 2 - 1, 0, cv.W // 2 + 1, cv.H, GUN)
        cv.bevel(0, 0, cv.W, cv.H)
        cv.clean[:] = 1
        return 'none'

    return fn


def interior(c=C('#B9BEC5')):
    def fn(cv):
        cv.fill(c)
        cv.a *= (1 + 0.05 * cv.lownoise(0.3))[..., None]
        for y in range(int(0.3 * cv.sy), cv.H, max(6, int(0.45 * cv.sy))):
            cv.mul(0, y, cv.W, y + 1, 0.8)
        cv.bevel(0, 0, cv.W, cv.H, 1.1, 0.8)
        return 'paint'

    return fn


def seat(c=C('#33485E')):
    def fn(cv):
        cv.fill(c)
        cv.a *= (1 + 0.08 * cv.lownoise(0.15))[..., None]
        cv.mul(0, 0, cv.W, 1, 1.35)
        cv.rect(cv.W // 2, 1, cv.W // 2 + 1, cv.H - 1, c * 0.6)
        cv.bevel(0, 0, cv.W, cv.H)
        return 'rough'

    return fn



def lamp_image(core, mid, edge, glow_a=0.0, off=False):
    n = 16
    yy, xx = np.mgrid[0:n, 0:n]
    cx = cy = (n - 1) / 2
    d = np.hypot(xx - cx, yy - cy)
    img = np.zeros((n, n, 4), np.float32)
    img[..., :3] = C('#15171B')
    img[..., 3] = 255
    # faint bevel of the dark square housing
    img[0, :, :3] *= 1.5
    img[:, 0, :3] *= 1.3
    img[-1, :, :3] *= 0.6
    img[:, -1, :3] *= 0.7
    # bezel ring
    ring = (d > 6.2) & (d <= 7.4)
    img[ring, :3] = C('#2F3339')
    img[(d > 7.0) & (d <= 7.6), :3] = C('#0B0C0E')
    lens = d <= 6.2
    t = np.clip(d / 6.2, 0, 1)
    core, mid, edge = np.asarray(core, np.float32), np.asarray(mid, np.float32), np.asarray(edge, np.float32)
    col = np.where((t < 0.55)[..., None], core + (mid - core) * (t / 0.55)[..., None],
                   mid + (edge - mid) * ((t - 0.55) / 0.45)[..., None])
    # glossy off-centre highlight (upper left)
    hl = np.exp(-(((xx - 5.2) ** 2 + (yy - 5.0) ** 2) / 3.0))
    col = col + (255 - col) * (0.55 * hl)[..., None] * (0.5 if off else 1.0)
    img[lens, :3] = col[lens]
    # lens rim darkening
    rim = (d > 5.3) & (d <= 6.2)
    img[rim, :3] *= 0.78
    # tiny cross-light streak on the lower right
    st = (d < 5.6) & (xx + yy > 19)
    img[st, :3] = np.minimum(img[st, :3] * 1.08, 255)
    return Image.fromarray(np.clip(img, 0, 255).astype(np.uint8), 'RGBA')



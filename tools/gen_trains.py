def pane(tint=C('#5B93B5'), panels=3, frame=GUN):
    """Glazed wall: tinted glass with sky reflection, diagonal glare and steel mullions."""

    def fn(cv):
        cv.vgrad(0, 0, cv.W, cv.H, tint * 0.95, tint * 0.5)
        u = np.arange(cv.W)[None, :] + np.arange(cv.H)[:, None] * 0.8
        streak = (np.mod(u, 34) < 5)
        cv.a[streak] = cv.a[streak] * 0.82 + 255 * 0.18
        t = max(2, int(0.05 * min(cv.sx, cv.sy)))
        cv.frame(0, 0, cv.W, cv.H, frame, t)
        for i in range(1, panels):
            x = int(cv.W * i / panels)
            cv.rect(x - 1, 0, x + 1, cv.H, frame)
            cv.mul(x - 1, 0, x, cv.H, 1.3)
        cv.rect(0, cv.H // 2 - 1, cv.W, cv.H // 2 + 1, frame, 0.9)
        cv.bevel(0, 0, cv.W, cv.H)
        cv.clean[:] = 1
        return 'none'

    return fn



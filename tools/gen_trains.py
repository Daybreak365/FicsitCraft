def rect_line(X, Z, xa, xb, za, zb, t):
    """Mask of a rectangle outline of thickness t in (X, Z) world coordinates."""
    inside = (X >= xa) & (X < xb) & (Z >= za) & (Z < zb)
    inner = (X >= xa + t) & (X < xb - t) & (Z >= za + t) & (Z < zb - t)
    return inside & ~inner


def deck_marks(box, side, zones=(), studs=True, line=True, centre_line=None):
    """Deck top markings in world coordinates: tactile studs + safety line along the track edge, bay outlines."""

    def fn(cv):
        X, Y, Z = coords(cv, 'up', box)
        dist = (1.1 - X) if side == 'L' else (X - 3.9)
        if studs:
            dd = np.mod(dist - 0.12, 0.1) - 0.05
            zz = np.mod(Z, 0.1) - 0.05
            band = (dist >= 0.12) & (dist < 0.32)
            dot = band & (np.hypot(dd, zz) < 0.03)
            sh = 1.0 + 0.5 * (-(dd + zz) * 12)
            cv.a[dot] = YELLOW * np.clip(sh[dot], 0.7, 1.4)[:, None]
            cv.a[band & ~dot] *= 0.8
        if line:
            m = (dist >= 0.42) & (dist < 0.5)
            cv.a[m] = YELLOW
            cv.a[(dist >= 0.5) & (dist < 0.52)] *= 0.7
        for (za, zb, d0, d1, col) in zones:
            xa, xb = (1.1 - d1, 1.1 - d0) if side == 'L' else (3.9 + d0, 3.9 + d1)
            m = rect_line(X, Z, xa, xb, za, zb, 0.05)
            cv.a[m] = col
        if centre_line is not None:
            for zc in centre_line:
                m = (np.abs(Z - zc) < 0.03) & (dist > 0.55)
                cv.a[m] = YELLOW * 0.9

    return fn


def win(cx, cy, w, h, lit=True, tint=C('#4F86A8'), bars=1, seed=0):
    """Framed window: sky reflection above, a (warm, when lit) room interior with silhouettes below."""

    def fn(cv):
        ww, hh = min(w, cv.fw * 0.94), min(h, cv.fh * 0.94)
        x0, y0, x1, y1 = cv.px_rect(cx, cy, ww, hh)
        cv.rect(x0, y0, x1, y1, GUN)
        t = max(1, int(0.045 * cv.sx))
        ix0, iy0, ix1, iy1 = x0 + t, y0 + t, x1 - t, y1 - t
        if ix1 - ix0 < 3 or iy1 - iy0 < 3:
            return
        cv.vgrad(ix0, iy0, ix1, iy1, tint * (1.05 if lit else 0.8), tint * (0.42 if not lit else 0.5))
        if lit:
            g = np.zeros((cv.H, cv.W), np.float32)
            g[iy0 + (iy1 - iy0) // 3:iy1, ix0:ix1] = 1
            warm = C('#FFD48A')
            wob = (0.55 + 0.45 * cv.lownoise(0.2))
            k = (g * 0.5 * wob)[..., None]
            cv.a[:] = cv.a * (1 - k) + warm * k
            # silhouettes of people / fixtures
            rng = np.random.default_rng(seed + int(cx * 100))
            for _ in range(max(1, (ix1 - ix0) // 9)):
                sx = int(rng.uniform(ix0 + 2, ix1 - 4))
                hgt = int((iy1 - iy0) * rng.uniform(0.3, 0.5))
                cv.rect(sx, iy1 - hgt, sx + 2, iy1, DARK, 0.75)
                cv.rect(sx, iy1 - hgt - 2, sx + 2, iy1 - hgt, DARK, 0.75)
        # diagonal glare
        u = (np.arange(cv.W)[None, :] + np.arange(cv.H)[:, None] * 0.7)
        streak = (np.mod(u, 26) < 4) & (np.arange(cv.W)[None, :] >= ix0) & (np.arange(cv.W)[None, :] < ix1) \
            & (np.arange(cv.H)[:, None] >= iy0) & (np.arange(cv.H)[:, None] < iy1)
        cv.a[streak] = cv.a[streak] * 0.8 + 255 * 0.2
        for i in range(1, bars + 1):
            mx = ix0 + (ix1 - ix0) * i // (bars + 1)
            cv.rect(mx, iy0, mx + 1, iy1, GUN)
        cv.bevel(x0, y0, x1, y1)
        cv.clean[y0:y1, x0:x1] = 1

    return fn


def sliding_door(cx, w, h):
    """Bottom-aligned automatic double glass door: lit header, centre gap, push plates and a hazard sill."""

    def fn(cv):
        if not cv.fits(w, h, 1.0):
            return
        x0, _, x1, _ = cv.px_rect(cx, 0.5, w, h)
        y1 = cv.H - 1
        y0 = y1 - int(h * cv.sy)
        cv.rect(x0 - 2, y0 - 3, x1 + 2, y1, GUN)
        cv.rect(x0, y0, x1, y1, C('#173040'))
        mid = (x0 + x1) // 2
        for (a, b) in ((x0 + 1, mid - 1), (mid + 1, x1 - 1)):
            cv.vgrad(a, y0 + 1, b, y1 - 3, C('#5FA0C4'), C('#2A5670'))
            for k in range(0, (y1 - y0), 9):
                cv.rect(a, y0 + k, b, y0 + k + 2, (255, 255, 255), 0.12)
        cv.rect(mid - 1, y0, mid + 1, y1, BLACK)
        cv.rect(x0 - 2, y0 - 5, x1 + 2, y0 - 2, C('#EAB545'))
        cv.rect(mid - 2, (y0 + y1) // 2 - 3, mid - 1, (y0 + y1) // 2 + 3, STEEL_L)
        cv.rect(mid + 1, (y0 + y1) // 2 - 3, mid + 2, (y0 + y1) // 2 + 3, STEEL_L)
        u, v = cv.ub(), cv.vb()

class Side:
    """Mirror-aware placement on the left (x 0..1.1) or right (x 3.9..5) deck; s = distance from the OUTER edge."""

    def __init__(self, b, name, width=W_B):
        self.b, self.name, self.L, self.W = b, name, name == 'L', width
        self.outer = 'left' if self.L else 'right'
        self.inner = 'right' if self.L else 'left'

    def x(self, s):
        return s if self.L else self.W - s

    def box(self, s0, y0, z0, s1, y1, z1, inner=None, outer=None, **kw):
        xa, xb = self.x(s0), self.x(s1)
        faces = dict(kw)
        for key, face in (('inner', self.inner), ('outer', self.outer)):
            v = inner if key == 'inner' else outer
            if v is not None:
                faces[face] = v(face) if callable(v) else v
        for k, v in list(faces.items()):
            if callable(v):
                faces[k] = v(k)
        return self.b.box(min(xa, xb), y0, z0, max(xa, xb), y1, z1, **faces)

    def face_of(self, which):
        return self.outer if which == 'outer' else self.inner



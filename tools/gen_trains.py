def concrete(color=CONC, seam=1.5, ties=True, stain=0.0):
    """Poured concrete: formwork panels, tie holes, aggregate speckle."""

    def fn(cv):
        cv.fill(color)
        n = cv.lownoise(0.7) * 0.06 + cv.lownoise(0.22) * 0.045
        cv.a *= (1 + n)[..., None]
        sp = cv.rng.uniform(0, 1, (cv.H, cv.W))
        cv.a[sp > 0.982] *= 1.22
        cv.a[sp < 0.02] *= 0.72
        if cv.fw > 0.9 and cv.fh > 0.5:
            nx = max(1, int(round(cv.fw / seam)))
            for i in range(1, nx):
                x = int(i * cv.W / nx)
                cv.mul(x, 0, x + 1, cv.H, 0.62)
                cv.mul(x + 1, 0, x + 2, cv.H, 1.12)
        if cv.fh > 0.9:
            ny = max(1, int(round(cv.fh / 1.2)))
            for i in range(1, ny):
                y = int(i * cv.H / ny)
                cv.mul(0, y, cv.W, y + 1, 0.66)
        if ties and cv.fw > 0.6 and cv.fh > 0.4:
            for y in range(int(0.22 * cv.sy), cv.H - 2, max(6, int(0.5 * cv.sy))):
                for x in range(int(0.25 * cv.sx), cv.W - 2, max(6, int(0.5 * cv.sx))):
                    cv.rect(x, y, x + 2, y + 2, color * 0.72)
                    cv.rect(x, y, x + 1, y + 1, color * 0.55)
        if stain:
            m = np.clip(cv.lownoise(0.5) * 0.9, 0, 1)
            cv.a *= (1 - stain * m)[..., None]
        return 'rough'

    return fn



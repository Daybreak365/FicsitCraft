class TStore(Store):
    """Same as bldart.Store but with the `trn` texture namespace."""

    def save(self, img, name):
        h = hashlib.sha1(img.tobytes() + bytes(str(img.size), 'ascii')).hexdigest()
        if h in self.seen:
            return self.seen[h]
        name = name.lower()  # resource identifiers must be [a-z0-9/._-]; uppercase makes the whole model fail to load
        path = os.path.join(self.root, name + '.png')
        os.makedirs(os.path.dirname(path), exist_ok=True)
        img.save(path)
        rid = TID + name.replace(os.sep, '/')
        self.seen[h] = rid
        self.count += 1
        return rid


class Shared:
    """Pre-painted textures reused by many boxes (wheels, sleepers, rails ...): painted once, referenced by id."""

    def __init__(self, store):
        self.store = store
        self.cache = {}

    def get(self, key, spec, w, h, face='front'):
        if key not in self.cache:
            img = spec.paint(w, h, face, zlib.crc32(('trn-shared/' + key).encode()))
            self.cache[key] = self.store.save(img, 'shared/' + key)
        return self.cache[key]

    def img(self, key, img):
        if key not in self.cache:
            self.cache[key] = self.store.save(img, 'shared/' + key)
        return self.cache[key]


def coords(cv, face, box):
    """World (X, Y, Z) of every pixel centre of `face` of the box (x0,y0,z0,x1,y1,z1), following the game's UVs."""
    x0, y0, z0, x1, y1, z1 = box
    U = ((np.arange(cv.W) + 0.5) / cv.W)[None, :]
    V = ((np.arange(cv.H) + 0.5) / cv.H)[:, None]
    full = lambda a: np.broadcast_to(np.float32(a), (cv.H, cv.W))
    b = lambda a: np.broadcast_to(a.astype(np.float32), (cv.H, cv.W))
    if face == 'front':
        return b(x1 - U * (x1 - x0)), b(y1 - V * (y1 - y0)), full(z1)
    if face == 'back':
        return b(x0 + U * (x1 - x0)), b(y1 - V * (y1 - y0)), full(z0)
    if face == 'left':
        return full(x0), b(y1 - V * (y1 - y0)), b(z1 - U * (z1 - z0))
    if face == 'right':
        return full(x1), b(y1 - V * (y1 - y0)), b(z0 + U * (z1 - z0))
    if face == 'up':
        return b(x0 + U * (x1 - x0)), full(y1), b(z1 - V * (z1 - z0))
    return b(x0 + U * (x1 - x0)), full(y0), b(z1 - V * (z1 - z0))


def zu(face, t):
    """u fraction of a feature that sits at fraction t from the FRONT of a side face (left: u runs front->back)."""
    return t if face == 'left' else 1.0 - t



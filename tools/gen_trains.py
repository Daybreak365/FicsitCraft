def gen_railway_icon():
    """Curved steel track piece: two rails bent through a quarter turn, tied together by wooden sleepers.
    Drawn 8x oversampled and snapped to a 16x16 palette so the shapes stay clean pixel art."""
    n, ss = 16, 8
    cx, cy = 16.9 * ss, 16.9 * ss            # centre of the bend (lower right)
    r_in, r_out = 8.3 * ss, 13.9 * ss        # rail centre lines
    HI, MID, LO = C('#EEF2F5'), C('#B2BAC2'), C('#6E777F')
    SLP, SLP_L, SLP_D = C('#8E5F37'), C('#B98652'), C('#54371F')
    from PIL import ImageDraw

    def layer():
        return Image.new('L', (n * ss, n * ss), 0)

    L = {k: layer() for k in ('slp', 'slp_l', 'slp_d', 'lo', 'mid', 'hi')}
    D = {k: ImageDraw.Draw(v) for k, v in L.items()}
    nk = 5
    for k in range(nk):
        a = math.pi + (math.pi / 2) * (k + 0.5) / nk
        c, s_ = math.cos(a), math.sin(a)
        r0, r1 = r_in - 1.6 * ss, r_out + 1.6 * ss
        p0 = (cx + c * r0, cy + s_ * r0)
        p1 = (cx + c * r1, cy + s_ * r1)
        D['slp'].line([p0, p1], fill=255, width=int(1.9 * ss))
        # lit upper-left edge and dark end grain
        t = (-s_, c)
        q0 = (p0[0] - t[0] * 0.8 * ss, p0[1] - t[1] * 0.8 * ss)
        q1 = (p1[0] - t[0] * 0.8 * ss, p1[1] - t[1] * 0.8 * ss)
        D['slp_l'].line([q0, q1], fill=255, width=int(0.9 * ss))
        D['slp_d'].line([(cx + c * r0, cy + s_ * r0), (cx + c * (r0 + 0.9 * ss), cy + s_ * (r0 + 0.9 * ss))], fill=255, width=int(2.3 * ss))
        D['slp_d'].line([(cx + c * (r1 - 0.9 * ss), cy + s_ * (r1 - 0.9 * ss)), (cx + c * r1, cy + s_ * r1)], fill=255, width=int(2.3 * ss))
    for rr in (r_in, r_out):
        for key, dr, w in (('lo', -0.55 * ss, 1.0 * ss), ('mid', 0.05 * ss, 0.9 * ss), ('hi', 0.65 * ss, 0.9 * ss)):
            r = rr + dr
            D[key].arc([cx - r, cy - r, cx + r, cy + r], 180, 270, fill=255, width=int(w))
    cov = {k: np.asarray(v, np.float32).reshape(n, ss, n, ss).mean(axis=(1, 3)) / 255 for k, v in L.items()}
    out = np.zeros((n, n, 4), np.uint8)
    for y in range(n):
        for x in range(n):
            col = None
            if cov['slp'][y, x] > 0.45:
                col = SLP
                if cov['slp_l'][y, x] > 0.45:
                    col = SLP_L
                if cov['slp_d'][y, x] > 0.5:
                    col = SLP_D
            for key, c in (('lo', LO), ('mid', MID), ('hi', HI)):
                if cov[key][y, x] > 0.5:
                    col = c
            if col is not None:
                out[y, x] = (*[int(v) for v in col], 255)
    # fill the enclosed gaps of the ladder with dark ballast so the piece reads as one solid object
    inside = np.zeros((n, n), bool)
    yy, xx = np.mgrid[0:n, 0:n]
    dd = np.hypot(xx + 0.5 - cx / ss, yy + 0.5 - cy / ss)
    aa = np.arctan2(yy + 0.5 - cy / ss, xx + 0.5 - cx / ss) % (2 * math.pi)
    bed = (aa >= math.pi - 0.02) & (aa <= 1.5 * math.pi + 0.02) & (dd >= r_in / ss - 1.6) & (dd <= r_out / ss + 1.6)
    for y in range(n):
        for x in range(n):
            if bed[y, x] and out[y, x, 3] == 0:
                out[y, x] = (0x4A, 0x4E, 0x55, 255) if (x + y) % 5 else (0x5A, 0x5F, 0x66, 255)
    src = out.copy()
    for y in range(n):
        for x in range(n):
            if src[y, x, 3] == 0:
                for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    nx, ny = x + dx, y + dy
                    if 0 <= nx < n and 0 <= ny < n and src[ny, nx, 3] > 0:
                        out[y, x] = (18, 20, 24, 255)
                        break
    save_png(Image.fromarray(out, 'RGBA'), os.path.join(ITEM_TEX, 'railway.png'), '16x16 item icon: curved steel track piece')
    write_json(os.path.join(ITEM_MODELS, 'railway.json'),
               {'parent': 'minecraft:item/generated', 'textures': {'layer0': 'ficsitcraft:item/railway'}},
               'item model for the Railway item', indent=2)


